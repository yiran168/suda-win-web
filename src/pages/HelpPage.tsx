          <li><b>批次纸张设置</b>：列表上方「修改纸张」可像新建画布一样改纸型（连续/标签）、纸宽与标签尺寸、窄纸装入位置、打印后走纸——确认后<b>按新纸张自动重新排版填充与分页</b>（例如换成 40×30 标签纸，内容会重新切片成一张张标签）。本设置只影响当前批次，不改全局「设备校准」；若有手动编辑过的页，重新排版前会先提示确认。</li>
