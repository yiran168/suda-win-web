          <li>PDF 每页按纸宽等比渲染成图片元素；Word 走<b>自研解析排版引擎</b>（不依赖任何外部软件）：保留段落、标题、真实字号、上下标、有序/无序列表（含 Word 编号模板）、表格（列宽比例、嵌套表格）、图片、<b>分栏版式</b>、<b>文本框</b>（就近放置加边框）与<b>常用公式</b>（分数、上下标、根式、括号、求和/积分上下限、矩阵）；PPT 提取每页文字与配图；Excel 转为可编辑表格；TXT 自动判断编码（UTF-8 / UTF-16 / GB18030）并按纸宽换行分页。</li>
